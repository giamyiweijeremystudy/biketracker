function haversineM(lat1, lon1, lat2, lon2) {
  const R = 6371000
  const dLat = (lat2 - lat1) * Math.PI / 180
  const dLon = (lon2 - lon1) * Math.PI / 180
  const a = Math.sin(dLat/2)**2 + Math.cos(lat1*Math.PI/180)*Math.cos(lat2*Math.PI/180)*Math.sin(dLon/2)**2
  return 2 * R * Math.atan2(Math.sqrt(a), Math.sqrt(1-a))
}

// Point-to-segment distance (approximate, for small distances)
function distToSegment(p, a, b) {
  const dx = b.lng - a.lng, dy = b.lat - a.lat
  const lenSq = dx*dx + dy*dy
  if (lenSq === 0) return haversineM(p.lat, p.lng, a.lat, a.lng)
  const t = Math.max(0, Math.min(1, ((p.lng - a.lng)*dx + (p.lat - a.lat)*dy) / lenSq))
  return haversineM(p.lat, p.lng, a.lat + t*dy, a.lng + t*dx)
}

/**
 * Find the best park to route through between start and end.
 * Returns { entry, exit } waypoints, or null if no suitable park found.
 *
 * Strategy:
 * - Find parks whose center is within MAX_DETOUR of the direct route line
 * - Pick the one closest to the midpoint
 * - Return its best entry point (closest to start) and exit point (closest to end)
 */
export function findBestParkWaypoints(start, end) {
  const directDist = haversineM(start.lat, start.lng, end.lat, end.lng)
  const MAX_DETOUR = Math.min(directDist * 0.6, 2500) // max 60% of route or 2.5km

  let bestPark = null
  let bestScore = Infinity

  for (const park of SG_PARKS) {
    const c = park.center
    // How far is this park center from the direct line?
    const distFromLine = distToSegment(c, start, end)
    if (distFromLine > MAX_DETOUR) continue

    // Score by distance from midpoint along the route
    const mid = { lat: (start.lat + end.lat) / 2, lng: (start.lng + end.lng) / 2 }
    const score = haversineM(c.lat, c.lng, mid.lat, mid.lng)
    if (score < bestScore) {
      bestScore = score
      bestPark = park
    }
  }

  if (!bestPark) return null

  // Find the entry point closest to start
  const entry = bestPark.entries.reduce((best, e) => {
    const d = haversineM(start.lat, start.lng, e.lat, e.lng)
    return d < best.d ? { e, d } : best
  }, { e: bestPark.entries[0], d: Infinity }).e

  // Find the exit point closest to end (different from entry if possible)
  const exit = bestPark.entries.reduce((best, e) => {
    if (e === entry) return best
    const d = haversineM(end.lat, end.lng, e.lat, e.lng)
    return d < best.d ? { e, d } : best
  }, { e: bestPark.entries[0], d: Infinity }).e

  return { entry, exit, parkName: bestPark.name }
}
